// UpdatePartStatus advances a part and stamps the date that goes with the new
// state.
//
// The date is derived from the status rather than supplied, for the same reason
// resolved_at is: a part marked received with no received_on is a gap nobody
// notices until they are trying to work out why a repair took three weeks. on
// may be the zero time, in which case today is used.
func (s *ServiceTicketStore) UpdatePartStatus(ctx context.Context, tx pgx.Tx, id uuid.UUID, status domain.ServicePartStatus, on time.Time) (*domain.ServicePart, error) {
	if on.IsZero() {
		on = time.Now()
	}
	var ordered, received, installed *time.Time
	switch status {
	case domain.ServicePartStatusOrdered:
		ordered = &on
	case domain.ServicePartStatusReceived:
		received = &on
	case domain.ServicePartStatusInstalled:
		installed = &on
	}

	// COALESCE keeps the earlier stamps: a part that is installed still has to
	// remember when it was ordered.
	row := tx.QueryRow(ctx,
		`UPDATE service_parts
		 SET status = $2,
		     ordered_on   = COALESCE($3, ordered_on),
		     received_on  = COALESCE($4, received_on),
		     installed_on = COALESCE($5, installed_on),
		     updated_at   = now()
		 WHERE id = $1
		 RETURNING `+servicePartColumns,
		id, string(status), ordered, received, installed)

	part, err := scanServicePart(row)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, err
		}
		return nil, fmt.Errorf("update service part %s status: %w", id, err)
	}
	return part, nil
}

// DeletePart removes a part line. For fixing a mistyped entry — a part that was
// genuinely ordered and then cancelled is history worth keeping, so prefer
// leaving it and saying so in a note.
func (s *ServiceTicketStore) DeletePart(ctx context.Context, tx pgx.Tx, id uuid.UUID) error {
	if _, err := tx.Exec(ctx, `DELETE FROM service_parts WHERE id = $1`, id); err != nil {
		return fmt.Errorf("delete service part %s: %w", id, err)
	}
	return nil
}

