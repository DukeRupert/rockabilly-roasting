// TouchContact records that somebody talked to the customer about this ticket.
//
// Only ever moves the timestamp forward. A note logged late — Tuesday's call
// written up on Thursday — must not drag the clock backwards and make a ticket
// look staler than it is.
func (s *ServiceTicketStore) TouchContact(ctx context.Context, tx pgx.Tx, id uuid.UUID, at time.Time) error {
	_, err := tx.Exec(ctx,
		`UPDATE service_tickets SET last_contact_at = $2, updated_at = now()
		 WHERE id = $1 AND last_contact_at < $2`,
		id, at)
	if err != nil {
		return fmt.Errorf("touch service ticket %s contact: %w", id, err)
	}
	return nil
}

